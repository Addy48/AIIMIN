/**
 * Notifications are generated by rules from real state (plan Part 2 §8), never
 * seeded. Each rule has a dedupe key so it fires once. Copy leads with what you
 * can gain, never with damage.
 */
@Singleton
class NotificationRepository @Inject constructor(
    @ApplicationContext private val context: Context,
    private val dao: NotificationDao,
    private val vault: VaultDao,
    private val tasks: TaskDao,
    private val calendar: CalendarDao,
    private val money: MoneyDao,
    private val ledger: aiimin.core.database.LedgerDao,
    private val life: LifeRepository,
    private val settings: SettingsStore,
    private val clock: DayClock,
) {
    val all = dao.all()
    val unread = dao.unread()
    suspend fun markAllRead() = dao.markAllRead()
    suspend fun dismiss(id: String) = dao.dismiss(id)

    suspend fun run() {
        // Older rows kept the old wording (streaks, "Rough patch"); reworded once (PRD 13.2, C-001).
        if (!settings.current().notificationsReworded) {
            dao.reword("battery:", "A lighter day", "Today your minimums are the tiny versions, and each counts double.")
            dao.rewordBody("streak:", "The tiny versions count. Keep what you can.")
            settings.update { it.copy(notificationsReworded = true) }
        }
        collapseRepeats()
        val today = clock.today()
        val now = LocalTime.now(clock.zone)

        // Documents expiring: 90 / 60 / 30 / 7 / 0 days, most urgent only.
        for (d in vault.withExpiry()) {
            val left = ChronoUnit.DAYS.between(today, LocalDate.parse(d.expires!!))
            val t = listOf(0L, 7L, 30L, 60L, 90L).firstOrNull { left <= it } ?: continue
            if (left < -7) continue
            val body = when {
                left < 0 -> "Expired ${-left} day${if (left == -1L) "" else "s"} ago. Renew and add the new copy."
                left == 0L -> "Expires today."
                else -> "Expires in $left days, on ${LocalDate.parse(d.expires).let { "${it.dayOfMonth} ${it.month.name.lowercase().replaceFirstChar(Char::uppercase).take(3)}" }}."
            }
            emit("doc:${d.id}:$t", d.title, body, "doc", d.id, if (t <= 30) 2 else 1)
        }

        // NT23 · vault backup overdue: 14 days without one (and again at 30), only once there are documents.
        val docsHeld = vault.allNow().count { !it.deleted }
        if (docsHeld > 0) {
            val last = context.getSharedPreferences(aiimin.core.data.vault.VaultBackupRepository.PREFS, Context.MODE_PRIVATE).getLong("last_at", 0L)
            val days = if (last == 0L) null else ChronoUnit.DAYS.between(java.time.Instant.ofEpochMilli(last).atZone(clock.zone).toLocalDate(), today)
            val step = when { days == null -> "never"; days >= 30 -> "30"; days >= 14 -> "14"; else -> null }
            if (step != null) emit("backup:$step", "Back up your vault", if (days == null) "Your documents live only on this phone. Keep a backup somewhere you trust." else "Last backup $days days ago.", "backup", null, 1)
        }

        // NT2 · a confirmed bill due tomorrow (reminder on, not AutoPay).
        for (b in ledger.billsNow().filter { it.status == "CONFIRMED" && it.remind && !it.autopay }) {
            if (LocalDate.parse(b.nextDue) == today.plusDays(1)) {
                emit("bill:${b.id}:${b.nextDue}", "${b.title} ${aiimin.core.data.util.Money.whole(b.amountPaise)} is due tomorrow", "Mark it paid in Bills once it's done.", "bills", b.id, 1)
            }
        }

        // Events starting within 15 minutes.
        val nowMs = System.currentTimeMillis()
        calendar.betweenNow(nowMs, nowMs + 15 * 60_000L).filter { !it.allDay && it.startAt >= nowMs }.forEach {
            emit("event:${it.id}", it.title, "Starts at ${aiimin.core.data.util.Dates.clock(java.time.Instant.ofEpochMilli(it.startAt).atZone(clock.zone).toLocalTime())}.", "today", it.id, 2)
        }

        // A timed task that passed half an hour ago — gentle, once.
        tasks.forDayNow(today.toString()).filter { !it.done && it.time != null && it.assignee == null }.forEach { t ->
            val at = runCatching { LocalTime.parse(t.time) }.getOrNull() ?: return@forEach
            if (now.isAfter(at.plusMinutes(30))) emit("task:${t.id}:$today", "Still on for today", t.title, "today", t.id, 1)
        }

        // Evening: minimums at risk. Lead with the gain.
        val view = runCatching { life.compute() }.getOrNull()
        if (view != null && now.hour >= 20) {
            val m = view.today.minimums
            val left = m.planned - m.kept
            if (left > 0 && !view.today.paused) {
                emit("streak:$today", "$left minimum${if (left == 1) "" else "s"} left today", minimumsNudgeBody(left), "today", null, 2)
            }
        }
        if (view?.battery?.state == BatteryState.LOW) {
            emit("battery:$today", "A lighter day", "Today your minimums are the tiny versions, and each counts double.", "today", null, 1)
        }

        // Budget pace on the personal ledger.
        val ym = YearMonth.from(today)
        money.budgetNow(ym.toString())?.let { b ->
            val spent = money.betweenNow(ym.atDay(1).toString(), today.toString()).filter { it.ledger == "PERSONAL" && it.direction == "out" }.sumOf { it.amountPaise }
            if (b.totalPaise > 0) {
                val share = spent * 100 / b.totalPaise
                when {
                    share >= 100 -> emit("budget:$ym:100", "Month plan reached", "${Money.format(spent)} of ${Money.format(b.totalPaise)} spent.", "money", null, 1)
                    share >= 80 -> emit("budget:$ym:80", "80% of the month plan used", "${Money.format(b.totalPaise - spent)} left for ${ym.lengthOfMonth() - today.dayOfMonth + 1} days.", "money", null, 1)
                }
            }
        }

        // Review inbox.
        val pending = money.pendingDraftsNow().size
        if (pending > 0) emit("inbox:$today", "$pending payment${if (pending == 1) "" else "s"} to review", "Detected from your bank alerts. Nothing is booked until you settle it.", "money", null, 0)

        // Weekly review, Sunday evening.
        if (today.dayOfWeek == DayOfWeek.SUNDAY && now.hour >= 18) {
            emit("review:${today.get(IsoFields.WEEK_BASED_YEAR)}-W%02d".format(java.util.Locale.ROOT, today.get(IsoFields.WEEK_OF_WEEK_BASED_YEAR)), "Your week, in one screen", "Five minutes to close the week and set up the next.", "score", null, 0)
        }
    }

    /**
     * Rules keyed by day ("inbox:2026-10-17", "task:<id>:2026-10-17") fire again each day; only the
     * newest of each family stays in the list, so yesterday's "6 payments to review" never piles up.
     */
    private suspend fun collapseRepeats() {
        val stale = dao.openNow().groupBy { family(it.ruleKey) }.values.flatMap { g -> g.sortedByDescending { it.at }.drop(1) }
        if (stale.isNotEmpty()) dao.dismissAll(stale.map { it.id })
    }

    /** A one-off notice from a finished job (a whole-year SMS import). Opens [route] when tapped. */
    suspend fun announce(key: String, title: String, body: String, route: String) = emit(key, title, body, route, null, 1)

    private suspend fun emit(key: String, title: String, body: String, route: String, arg: String?, priority: Int) {
        val n = NotificationEntity(newId(), key, title, body, System.currentTimeMillis(), route, arg, priority)
        if (dao.insertIfNew(n) == -1L) return
        collapseRepeats()
        val s = settings.current()
        val mins = LocalTime.now(clock.zone).let { it.hour * 60 + it.minute }
        val quiet = s.quiet.enabled && if (s.quiet.fromMin <= s.quiet.toMin) mins in s.quiet.fromMin until s.quiet.toMin else mins >= s.quiet.fromMin || mins < s.quiet.toMin
        // Quiet hours hold back low and medium; high still comes through.
        if (priority == 0 || (quiet && priority < 2)) return
        post(n, raahiArt = aiimin.core.engine.raahi.RaahiMode.of(s.raahiMode) != aiimin.core.engine.raahi.RaahiMode.OFF)
    }

    private fun post(n: NotificationEntity, raahiArt: Boolean) {
        if (Build.VERSION.SDK_INT >= 33 && ContextCompat.checkSelfPermission(context, Manifest.permission.POST_NOTIFICATIONS) != PackageManager.PERMISSION_GRANTED) return
        ensureChannels(context)
        val launch = context.packageManager.getLaunchIntentForPackage(context.packageName)?.apply {
            putExtra(EXTRA_ROUTE, n.route)
            putExtra(EXTRA_ARG, n.routeArg)
            addFlags(Intent.FLAG_ACTIVITY_SINGLE_TOP or Intent.FLAG_ACTIVITY_CLEAR_TOP)
        }
        val pi = launch?.let { PendingIntent.getActivity(context, n.ruleKey.hashCode(), it, PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT) }
        val notif = NotificationCompat.Builder(context, if (n.priority >= 2) CH_HIGH else CH_DEFAULT)
            // PRD 1.1 and 20.4: money and document notices are signed AIIMIN (its mark, no character); the rest
            // speak as Raahi, with its face as the large icon unless Raahi is Off.
            .setSmallIcon(if (signedAiimin(n.ruleKey, n.route)) R.drawable.ic_stat_aiimin else R.drawable.ic_stat_raahi)
            .apply { if (raahiArt && !signedAiimin(n.ruleKey, n.route)) setLargeIcon(android.graphics.BitmapFactory.decodeResource(context.resources, R.drawable.raahi_notif_large)) }
            .setContentTitle(n.title)
            .setContentText(n.body)
            .setStyle(NotificationCompat.BigTextStyle().bigText(n.body))
            .setContentIntent(pi)
            .setAutoCancel(true)
            .setPriority(if (n.priority >= 2) NotificationCompat.PRIORITY_HIGH else NotificationCompat.PRIORITY_DEFAULT)
            .build()
        runCatching { NotificationManagerCompat.from(context).notify(n.ruleKey.hashCode(), notif) }
    }

    companion object {
        const val CH_HIGH = "aiimin_important"
        const val CH_DEFAULT = "aiimin_general"
        const val CH_FOCUS = "aiimin_focus"
        const val EXTRA_ROUTE = "aiimin.route"
        const val EXTRA_ARG = "aiimin.arg"

        fun ensureChannels(context: Context) {
            val nm = context.getSystemService(NotificationManager::class.java)
            nm.createNotificationChannel(NotificationChannel(CH_HIGH, "Important", NotificationManager.IMPORTANCE_HIGH).apply { description = "Expiring documents, events starting, minimums left today" })
            nm.createNotificationChannel(NotificationChannel(CH_DEFAULT, "General", NotificationManager.IMPORTANCE_DEFAULT).apply { description = "Budget pace, reminders, review" })
            nm.createNotificationChannel(NotificationChannel(CH_FOCUS, "Focus timer", NotificationManager.IMPORTANCE_LOW).apply { description = "The running focus session" })
        }
    }
}

/**
 * "inbox:2026-10-17" → "inbox:", "task:abc:2026-10-17" → "task:abc:", "review:2026-W42" → "review:" (and the
 * old "review:42" week keys, D-045); keys without a date or week are their own family.
 */
/** Notices about money, documents and backups are signed AIIMIN, never Raahi (PRD 1.1, 20.5). */
fun signedAiimin(ruleKey: String, route: String? = null): Boolean =
    route in setOf("money", "bills", "vault", "doc", "backup") || ruleKey.substringBefore(':') in setOf("doc", "backup", "bill", "budget", "inbox", "smsyear")

internal fun family(ruleKey: String): String {
    val last = ruleKey.substringAfterLast(':', "")
    val periodic = Regex("\\d{4}-\\d{2}-\\d{2}|\\d{4}-W\\d{2}").matches(last) || (ruleKey.startsWith("review:") && last.all { it.isDigit() } && last.isNotEmpty())
    return if (periodic) ruleKey.substringBeforeLast(':') + ":" else ruleKey
}

/** The evening minimums reminder's second line (PRD 13.2: no streaks, no guilt; C-001). */
fun minimumsNudgeBody(left: Int): String =
    if (left == 1) "Keep it if you can. The tiny version counts." else "Keep them if you can. The tiny versions count."
